test_that("workbook reading preserves positions and mixed types", {
  skip_if_not_installed("readxl"); skip_if_not_installed("openxlsx")
  path <- tempfile(fileext = ".xlsx"); on.exit(unlink(path))
  wb <- openxlsx::createWorkbook(); openxlsx::addWorksheet(wb, "Second"); openxlsx::addWorksheet(wb, "First")
  openxlsx::writeData(wb, "Second", "001", startRow = 2, startCol = 2, colNames = FALSE)
  openxlsx::writeData(wb, "Second", 12, startRow = 3, startCol = 2, colNames = FALSE)
  openxlsx::writeData(wb, "Second", " NA ", startRow = 4, startCol = 2, colNames = FALSE)
  openxlsx::writeData(wb, "First", TRUE, colNames = FALSE)
  openxlsx::saveWorkbook(wb, path)
  stages <- character()
  data <- read_validation_workbook(path, function(stage, expression) {
    stages <<- c(stages, stage)
    force(expression)
  })
  expect_identical(stages, c("read.sheets", "read.worksheets"))
  expect_identical(names(data), c("Second", "First"))
  expect_identical(dim(data$Second), c(4L, 2L))
  expect_identical(data$Second[[2]][[2]], "001")
  expect_identical(data$Second[[2]][[3]], 12)
  expect_identical(data$Second[[2]][[4]], " NA ")
  expect_true(is.na(data$Second[[1]][[1]]))
  expect_true(data$First[[1]][[1]])
})

test_that("reading uses cached formula values and treats Excel errors as missing", {
  skip_if_not_installed("openxlsx"); skip_if_not_installed("xml2"); skip_if_not_installed("readxl")
  directory <- tempfile(); dir.create(directory)
  on.exit(unlink(directory, recursive = TRUE))
  path <- file.path(directory, "stored-values.xlsx")
  wb <- openxlsx::createWorkbook(); openxlsx::addWorksheet(wb, "Values")
  openxlsx::writeData(wb, "Values", c("anchor", "cached", "uncached", "error", "tail"), colNames = FALSE)
  openxlsx::writeFormula(wb, "Values", "40+2", startRow = 2)
  openxlsx::writeFormula(wb, "Values", "1+1", startRow = 3)
  openxlsx::saveWorkbook(wb, path)
  parts <- file.path(directory, "parts"); dir.create(parts)
  utils::unzip(path, exdir = parts)
  sheet <- file.path(parts, "xl/worksheets/sheet1.xml")
  xml <- xml2::read_xml(sheet)
  cached <- xml2::xml_find_first(xml, "//*[local-name()='c'][@r='A2']")
  xml2::xml_set_attr(cached, "t", "n")
  xml2::xml_remove(xml2::xml_find_all(cached, "./*[local-name()='v']"))
  xml2::xml_add_child(cached, "v", "42")
  error <- xml2::xml_find_first(xml, "//*[local-name()='c'][@r='A4']")
  xml2::xml_set_attr(error, "t", "e")
  xml2::xml_set_text(xml2::xml_find_first(error, "./*[local-name()='v']"), "#DIV/0!")
  xml2::write_xml(xml, sheet)
  old <- setwd(parts); on.exit(setwd(old), add = TRUE)
  utils::zip(path, list.files('.', recursive = TRUE, all.files = TRUE, no.. = TRUE), flags = "-q")
  setwd(old)
  before <- tools::md5sum(path)
  data <- read_validation_workbook(path)
  expect_identical(data$Values[[1]][[2]], 42)
  expect_true(is.na(data$Values[[1]][[3]]))
  expect_true(is.na(data$Values[[1]][[4]]))
  expect_identical(data$Values[[1]][[5]], "tail")
  expect_identical(tools::md5sum(path), before)
})

test_that("Excel dates are prepared only through the explicit conversion policy", {
  skip_if_not_installed("readxl"); skip_if_not_installed("openxlsx")
  path <- tempfile(fileext = ".xlsx"); on.exit(unlink(path))
  wb <- openxlsx::createWorkbook(); openxlsx::addWorksheet(wb, "Values")
  openxlsx::writeData(wb, "Values", as.Date("2023-01-02"), startRow = 1, colNames = FALSE)
  openxlsx::writeData(wb, "Values", as.POSIXct("2023-01-02 12:00:00", tz = "UTC"),
                      startRow = 2, colNames = FALSE)
  openxlsx::saveWorkbook(wb, path)
  raw <- read_validation_workbook(path)
  expect_s3_class(raw$Values[[1]][[1]], "POSIXct")
  data <- prepare_validation_data(raw, field_model("date"))
  expect_identical(data$Values[[1]][[1]], as.Date("2023-01-02"))
  expect_s3_class(data$Values[[1]][[2]], "POSIXct")
  expect_identical(format(data$Values[[1]][[2]], "%H:%M", tz = "UTC"), "12:00")
})
